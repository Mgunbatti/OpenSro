"""Extract the publisher key of the _CertifyUser call from GatewayServer.exe.

The certification handlers of GatewayServer (JMX_CommonServers/GatewayServer/CertifyDB.cpp) call
the stored procedure _CertifyUser with the account name, the password hash and a fixed key as
third argument. The key is not part of this repository. This script reads it from your own copy
of GatewayServer.exe:

    py tools\gen_certify_constants.py <path to GatewayServer.exe> [output .inl]

Without an output path it writes JMX_CommonServers/GatewayServer/CertifyConstants.inl (ignored by
git); the Makefile compiles it in when the file exists. Only the GatewayServer.exe the address
was taken from is accepted.

Where the value is: the SQL format string of _CertifyUser in .rdata (one string, used by three
handlers), "exec _CertifyUser '%s','%s','<key>'". The key is the text between the third pair of
quotes. The script never prints it.
"""
import hashlib
import os
import re
import struct
import sys

EXPECTED_SHA256 = 'f7a7770b074f880885e7f43274362107a1d07338949c7c5b68e32a5c7df391cc'
CERTIFY_USER_SQL_VA = 0x4DA0EC
PREFIX = b"exec _CertifyUser '%s','%s','"
SUFFIX = b"'"


def va_to_offset(data, va):
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    nsec = struct.unpack_from('<H', data, pe + 6)[0]
    opt = struct.unpack_from('<H', data, pe + 20)[0]
    base = struct.unpack_from('<I', data, pe + 52)[0]
    for i in range(nsec):
        sec = pe + 24 + opt + 40 * i
        vsize, vaddr, rsize, raddr = struct.unpack_from('<IIII', data, sec + 8)
        rva = va - base
        if vaddr <= rva < vaddr + max(vsize, rsize):
            return raddr + rva - vaddr
    raise ValueError('address 0x%X not in any section' % va)


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    data = open(sys.argv[1], 'rb').read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit('unexpected GatewayServer.exe (sha256 %s)' % digest)

    off = va_to_offset(data, CERTIFY_USER_SQL_VA)
    end = data.index(b'\0', off)
    sql = data[off:end]
    if not sql.startswith(PREFIX) or not sql.endswith(SUFFIX):
        sys.exit('the _CertifyUser format string was not found at 0x%X' % CERTIFY_USER_SQL_VA)
    key = sql[len(PREFIX):-len(SUFFIX)]
    if not re.match(br'^[0-9A-Za-z]+$', key):
        sys.exit('unexpected characters in the key')

    out = sys.argv[2] if len(sys.argv) == 3 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), '..', 'JMX_CommonServers', 'GatewayServer',
        'CertifyConstants.inl')
    with open(out, 'w') as f:
        f.write('// generated by tools/gen_certify_constants.py from GatewayServer.exe %s\n'
                '// Do not commit this file.\n' % digest[:16])
        f.write('#define GATEWAY_CERTIFY_USER_KEY "%s"\n' % key.decode('ascii'))
    print('wrote', os.path.normpath(out), '(%d characters)' % len(key))


if __name__ == '__main__':
    main()
